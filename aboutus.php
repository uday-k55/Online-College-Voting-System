POSTAL BALLOT FACILITY: INCLUSIVE ELECTIONS  
Where there is a will, there is a way – and when voters cannot physically 
reach the Polling Station, the Polling Station will reach out to them! From 
enrollment to election, the Election Commission of India leaves no stone 
unturned in ensuring that no voter is left behind. It is in the pursuit of this 
endeavour that the facility of Postal Ballot was extended to PwD electors, senior 
citizens above the age of 80 years, officers on essential election duty as notified 
by the Commission and COVID-19 positive patients. 
22-Kalimpong, situated at a height of more than 1,200 metres above sea level 
in the eastern Himalayas is the only Assembly Constituency of the smallest 
District of Darjeeling, West Bengal. It is the determination of our polling officers 
buoyed by the commitment of the Election Commission of India that voters 
from this hilly district were reached out to despite the many hurdles of extreme 
climatic conditions and inaccessible terrain. 
106-year-old Pavitra Pradhan from Part No.86 in the Municipal area of 
Kalimpong AC and 82-year-old Bhuddiman Mukhia of Nokdara village who 
availed this facility for the first time were excited to provide a heartwarming 
welcome to the entire polling team. The family of 31-year-old Jivan Roy from 
the Lower Beong village of Gidabling Gram Panchayat witnessed the joy of their 
son voting for the first time despite his locomotor disability. The polling officials 
even reached out to the hidden hamlet Mansintar in a remote corner at the 
border of Bhutan - truly, no voter was left behind.  
With the announcement of the Postal Ballot facility, 45% of the flagged voters 
i.e 2400 electors applied for access to cast their votes by Postal Ballot. ECI was 
fully geared to fulfill the commitment to make the voting process easy, 
accessible, inclusive, safe and free & fair for all. Majority of the population of 
this area consists of various tribal and non-tribal groups like Lepcha, Bhutia, 
Tamang, Limbu, Sherpa, Dukpa, Yolmo, Mech, Santal, Sarki, Damai, Kami, 
Rai, Magar, Chettri, Gurung and others with Nepali as the lingua franca of the 
region.  
Considering the hilly terrain and hidden hamlets in the slopes, meticulous 
planning was done to cover each and every absentee voter within the stipulated 
time. The Polling Party comprising of two Polling Officers, Videographer, Micro 
Observer and half section of CAPF apart from State Police, started their journey 
on 5th April, 12 days ahead of poll. There was a well managed Distribution 
Centre at the District Treasury where Postal Ballots were split and handed over 
to the Polling Teams in the early morning under tight security. 
51 such polling parties were on the field, travelling by car and even by foot to 
reach the voters! The polling officials reaffirmed the faith of voters in democracy 
as they recorded the postal ballot votes. 
The success of any democratic process of election rests upon the sheer strong 
faith of electors in the democracy accompanied by the sheer grit and 
determination of election officials. Absentee voters were appreciative of the 
Postal Ballot facility given by the Election Commission in view of the pandemic. 
Undoubtedly, it has improved the total voter turnout percentage while ensuring 
that elections were accessible and inclusive for all.   ----Inputs from CEO West Bengal 
